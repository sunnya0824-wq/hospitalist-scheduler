export function demoTemplates(counts: Partial<Record<string, number[]>> = {}): ShiftTemplateDef[] {
  const out: ShiftTemplateDef[] = [];
  DEMO_LOCATIONS.forEach((loc, li) => {
    loc.templates.forEach((t, ti) => {
      const id = `${loc.code}:${t.code}`;
      out.push({
        id,
        locationId: loc.code,
        locationName: loc.name,
        locationCode: loc.code,
        locationSort: li,
        name: t.name,
        code: t.code,
        category: t.category,
        startTime: t.startTime,
        endTime: t.endTime,
        dailyCounts: counts[id] ?? t.dailyCounts,
        holidayCount: t.holidayCount ?? null,
        color: t.color,
        sortOrder: ti,
      });
    });
  });
  return out;
}

