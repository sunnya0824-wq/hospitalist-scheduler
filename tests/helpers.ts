const addDays = (iso: string, n: number) => {
  const d = new Date(iso + "T00:00:00Z");
  d.setUTCDate(d.getUTCDate() + n);
  return d.toISOString().slice(0, 10);
};

export interface PriorWork {
  physicianId: string;
  date: string;
  endDate: string;
  category: ShiftCategory;
}

/**
 * Re-derive every hard rule from scratch. Returns human-readable violations.
 * `exempt` = assignment ids/indexes that were pre-assigned (locked/manual) and
 * may legitimately break rules.
 */
export function validateSchedule(
  physicians: SchedulerPhysician[],
  assignments: AssignmentResult[],
  opts: { restDays?: number; prior?: PriorWork[]; allowOverMax?: boolean } = {}
): string[] {
  const rest = opts.restDays ?? 2;
  const errs: string[] = [];
  const byPhys = new Map<string, { date: string; endDate: string; category: ShiftCategory; auto: boolean; locationId: string }[]>();
  for (const a of assignments) {
    if (!a.physicianId) continue;
    const list = byPhys.get(a.physicianId) ?? [];
    list.push({ date: a.date, endDate: a.endDate, category: a.category, auto: a.isAutoGenerated, locationId: a.locationId });
    byPhys.set(a.physicianId, list);
  }
  for (const p of physicians) {
    const mine = byPhys.get(p.id) ?? [];
    const prior = (opts.prior ?? []).filter((x) => x.physicianId === p.id);
    const all = [...prior.map((x) => ({ ...x, auto: false, locationId: "" })), ...mine];
    const tag = (s: string) => `${p.fullName}: ${s}`;
    if (!p.active && mine.length) errs.push(tag("inactive but assigned"));
    if (!opts.allowOverMax && mine.filter((m) => m.auto).length && mine.length > p.maxShifts) {
      errs.push(tag(`${mine.length} shifts > max ${p.maxShifts}`));
    }
    const startCount = new Map<string, number>();
    for (const s of all) startCount.set(s.date, (startCount.get(s.date) ?? 0) + 1);
    for (const [d, n] of startCount) if (n > 1) errs.push(tag(`double-booked ${d}`));
    const nightStarts = new Set(all.filter((s) => s.category === "NIGHT").map((s) => s.date));
    const starts = new Set(all.map((s) => s.date));

    for (const s of mine) {
      if (p.timeOffDates.has(s.date)) errs.push(tag(`works on time off ${s.date}`));
      if (p.unavailableDates.has(s.date)) errs.push(tag(`works while unavailable ${s.date}`));
      if (s.category === "NIGHT" && !p.nightEligible) errs.push(tag(`night but not eligible ${s.date}`));
      if (s.category === "ADMIT" && !p.adminEligible) errs.push(tag(`admit but not eligible ${s.date}`));
      if (!p.eligibleLocations.has(s.locationId)) errs.push(tag(`not eligible for ${s.locationId} on ${s.date}`));
    }
    // Overnight overlap: anything starting on an overnight's end date must be
    // the next night of a block.
    for (const s of all) {
      if (s.endDate === s.date) continue;
      const next = all.find((x) => x.date === s.endDate);
      if (next && !(s.category === "NIGHT" && next.category === "NIGHT")) {
        errs.push(tag(`works ${next.date} while overnight from ${s.date} is still running`));
      }
    }
    // Rest after the last night of each block.
    for (const n of nightStarts) {
      if (nightStarts.has(addDays(n, 1))) continue; // not the end of a block
      for (let k = 1; k <= rest; k++) {
        if (starts.has(addDays(n, k))) errs.push(tag(`works ${addDays(n, k)}, inside rest after night block ending ${n}`));
      }
    }
    // Night block length and consecutive days.
    for (const n of nightStarts) {
      if (nightStarts.has(addDays(n, -1))) continue;
      let len = 1;
      while (nightStarts.has(addDays(n, len))) len++;
      if (len > p.maxConsecutiveNights) errs.push(tag(`night block of ${len} from ${n} (cap ${p.maxConsecutiveNights})`));
    }
    for (const d of starts) {
      if (starts.has(addDays(d, -1))) continue;
      let len = 1;
      while (starts.has(addDays(d, len))) len++;
      if (len > p.maxConsecutiveDays) errs.push(tag(`${len} days in a row from ${d} (cap ${p.maxConsecutiveDays})`));
    }
  }
  return [...new Set(errs)];
}

/** Night block lengths per physician (within the given assignments). */
export function nightBlocks(assignments: AssignmentResult[]): Map<string, number[]> {
  const nights = new Map<string, Set<string>>();
  for (const a of assignments) {
    if (!a.physicianId || a.category !== "NIGHT") continue;
    const s = nights.get(a.physicianId) ?? new Set();
    s.add(a.date);
    nights.set(a.physicianId, s);
  }
  const out = new Map<string, number[]>();
  for (const [id, set] of nights) {
    const blocks: number[] = [];
    for (const d of [...set].sort()) {
      if (set.has(addDays(d, -1))) continue;
      let len = 1;
      while (set.has(addDays(d, len))) len++;
      blocks.push(len);
    }
    out.set(id, blocks);
  }
  return out;
}
