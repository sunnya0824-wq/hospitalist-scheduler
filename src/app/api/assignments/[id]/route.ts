import { NextResponse } from "next/server";
import { prisma } from "@/lib/prisma";
import { toISODate } from "@/lib/scheduler";
import { checkManualAssignments } from "@/lib/assignment-check";
import { asObject } from "@/lib/config-validate";

export const dynamic = "force-dynamic";
export const runtime = "nodejs";

/**
 * Edit one assignment:
 *   - { physicianId }  change physician (marks manual). A rule break is
 *                      allowed — the person scheduling may know better — but
 *                      it is saved as a warning on the slot.
 *   - { isLocked }     toggle lock
 *   - { clear: true }  empty the slot
 */
export async function PATCH(req: Request, { params }: { params: { id: string } }) {
  const body = asObject(await req.json().catch(() => ({})));
  const current = await prisma.shiftAssignment.findUnique({ where: { id: params.id } });
  if (!current) return NextResponse.json({ error: "Assignment not found." }, { status: 404 });
  const data: Record<string, unknown> = {};

  if ("physicianId" in body) {
    const physicianId = body.physicianId ? String(body.physicianId) : null;
    data.physicianId = physicianId;
    data.isManual = Boolean(physicianId);
    data.isAutoGenerated = false;
    data.warnings = [];
    if (physicianId) {
      const exists = await prisma.physician.findUnique({ where: { id: physicianId }, select: { id: true } });
      if (!exists) return NextResponse.json({ error: "Physician not found." }, { status: 400 });
      const [why] = await checkManualAssignments(
        [
          {
            physicianId,
            slot: {
              id: current.id,
              date: toISODate(current.date),
              endDate: toISODate(current.endDate),
              category: current.category,
              locationId: current.locationId,
            },
          },
        ],
        [current.id]
      );
      if (why) data.warnings = [`Manual override: ${why}`];
    }
  }
  if ("isLocked" in body) data.isLocked = Boolean(body.isLocked);
  if (body.clear === true) {
    data.physicianId = null;
    data.isManual = false;
    data.isLocked = false;
    data.warnings = [];
  }

  const updated = await prisma.shiftAssignment.update({
    where: { id: params.id },
    data,
    include: { physician: { select: { id: true, fullName: true } } },
  });
  return NextResponse.json({
    id: updated.id,
    physicianId: updated.physicianId,
    physicianName: updated.physician?.fullName ?? null,
    isManual: updated.isManual,
    isLocked: updated.isLocked,
    isAutoGenerated: updated.isAutoGenerated,
    warnings: updated.warnings,
  });
}
