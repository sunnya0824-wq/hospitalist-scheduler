import { NextResponse } from "next/server";
import { prisma } from "@/lib/prisma";
import { toISODate } from "@/lib/scheduler";
import { checkManualAssignments, type SlotRef } from "@/lib/assignment-check";

export const dynamic = "force-dynamic";
export const runtime = "nodejs";

/**
 * Swap the physicians of two assignments. Both resulting assignments must
 * pass every hard rule (same rules as the generator); rejects with a reason.
 */
export async function POST(req: Request) {
  const body = await req.json().catch(() => ({}));
  const aId = String(body.a ?? "");
  const bId = String(body.b ?? "");
  if (!aId || !bId || aId === bId) {
    return NextResponse.json({ error: "Two distinct assignment ids are required." }, { status: 400 });
  }
  const rows = await prisma.shiftAssignment.findMany({ where: { id: { in: [aId, bId] } } });
  const a = rows.find((r) => r.id === aId);
  const b = rows.find((r) => r.id === bId);
  if (!a || !b) return NextResponse.json({ error: "Assignment not found." }, { status: 404 });

  const ref = (r: typeof a): SlotRef => ({
    id: r.id,
    date: toISODate(r.date),
    endDate: toISODate(r.endDate),
    category: r.category,
    locationId: r.locationId,
  });
  const proposals = [
    ...(b.physicianId ? [{ physicianId: b.physicianId, slot: ref(a) }] : []),
    ...(a.physicianId ? [{ physicianId: a.physicianId, slot: ref(b) }] : []),
  ];
  // Each physician's own vacated slot is ignored; when one person is on both
  // slots the swap is a no-op.
  const reasons = (await checkManualAssignments(proposals, [aId, bId])).filter(Boolean);
  if (reasons.length) {
    return NextResponse.json({ error: `Swap not allowed: ${reasons.join("; ")}` }, { status: 400 });
  }

  await prisma.$transaction([
    prisma.shiftAssignment.update({
      where: { id: aId },
      data: { physicianId: b.physicianId, isManual: Boolean(b.physicianId), isAutoGenerated: false, warnings: [] },
    }),
    prisma.shiftAssignment.update({
      where: { id: bId },
      data: { physicianId: a.physicianId, isManual: Boolean(a.physicianId), isAutoGenerated: false, warnings: [] },
    }),
  ]);
  return NextResponse.json({ ok: true });
}
